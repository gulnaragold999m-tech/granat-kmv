def category_title(flow: str, cat: str) -> str:
    """Человекочитаемое название категории по кодам flow/cat."""
    for code, title in FLOWS.get(flow, {}).get("categories", []):
        if code == cat:
            return title
    return cat


def category_brief(cat: str) -> str:
    """Бриф «логики обдумывания» для системного промпта."""
    return CATEGORY_BRIEFS.get(cat, "").strip()
