/* ── Поиск цены по таблице ─────────────────────────────────────
   Нужен, чтобы на первом экране сайта не появилось руками вписанное
   число. Строку не нашли — падаем при сборке. Это нарочно: пусть
   сборка сломается сейчас, чем клиент увидит цену из прошлого года. */

export function najti(t: TirazhTablica, stroka: string, kolonka = 0): Yacheyka {
  const s = t.stroki.find((r) => r.nazvanie === stroka);
  if (!s) throw new Error(`Прайс: в таблице «${t.zagolovok}» нет строки «${stroka}»`);
  const c = s.ceny[kolonka];
  if (c === undefined) {
    throw new Error(`Прайс: в строке «${stroka}» нет столбца № ${kolonka}`);
  }
  return c;
}

export function najtiPoziciyu(
  pozicii: readonly { nazvanie: string; cena: Yacheyka }[],
  nazvanie: string,
): Yacheyka {
  const p = pozicii.find((x) => x.nazvanie === nazvanie);
  if (!p) throw new Error(`Прайс: нет позиции «${nazvanie}»`);
  return p.cena;
}

