/* ── Как читаются цены ────────────────────────────────────────────
   number      — точная цена в рублях
   { ot: n }   — цена стартовая, печатается «от 10 ₽»
   { plus: n } — надбавка к основной услуге, печатается «+100 ₽»
   строка      — «по запросу», «—», «считаем отдельно» */
export type Yacheyka = number | { ot: number } | { plus: number } | string;

export interface Poziciya {
  nazvanie: string;
  cena: Yacheyka;
}

/** Тиражная таблица: цена зависит от количества. */
