/* ── Печать цены текстом ───────────────────────────────────────── */

function rubli(n: number): string {
  /* Пробел между тысячами ставим сами: toLocaleString в разных версиях
     Node подставляет то обычный пробел, то неразрывный, и цена в боте
     начинает отличаться от цены на сайте одним невидимым знаком. */
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ' ₽';
}

/** Одна ячейка прайса человеческим текстом: «40 ₽», «от 10 ₽», «+100 ₽». */
export function cenaTekstom(y: Yacheyka): string {
  if (typeof y === 'number') return rubli(y);
  if (typeof y === 'string') return y;
  if ('ot' in y) return 'от ' + rubli(y.ot);
  return '+' + rubli(y.plus);
}

/** Весь прайс простым текстом — для бота, для письма, для `npm run ceny`. */
export function prajsTekstom(): string {
  const s: string[] = [];

  s.push(STUDIYA.nazvanie);
  s.push(`${STUDIYA.adres} · ${STUDIYA.telefon}`);
  s.push(`${STUDIYA.chasy} · ${STUDIYA.ohvat}`);
  s.push('');

  s.push(FOTO_NA_DOKUMENTY.zagolovok.toUpperCase());
  s.push(FOTO_NA_DOKUMENTY.vvodnaya);
  for (const p of FOTO_NA_DOKUMENTY.pozicii) {
    s.push(`  ${p.nazvanie} — ${cenaTekstom(p.cena)}`);
  }
  for (const n of FOTO_NA_DOKUMENTY.primechaniya) s.push(`  ${n}`);
  s.push('');

  for (const r of RAZDELY) {
    s.push(`${r.zagolovok.toUpperCase()} (${r.edinica})`);
    s.push(`  ${r.pervyjStolbec}: ${r.kolonki.join(' | ')}`);
    for (const st of r.stroki) {
      s.push(`  ${st.nazvanie} — ${st.ceny.map(cenaTekstom).join(' | ')}`);
    }
    for (const n of r.primechaniya) s.push(`  ${n}`);
    s.push('');

    if (r.id === 'flaery') {
      s.push(NACENKA_ZA_PLOTNOST.zagolovok.toUpperCase());
      for (const p of NACENKA_ZA_PLOTNOST.stroki) {
        s.push(`  ${p.bumaga} — ${p.tekst}`);
      }
      for (const n of NACENKA_ZA_PLOTNOST.primechaniya) s.push(`  ${n}`);
      s.push('');
    }

    if (r.id === 'priglasheniya') {
      const i = PRIGLASHENIE_INDIVIDUALNOE;
      s.push(`${i.nazvanie.toUpperCase()} — ${cenaTekstom(i.cena)} за штуку`);
      for (const n of i.primechaniya) s.push(`  ${n}`);
      s.push('');

      s.push(`${MATERIAL_I_OTDELKA.zagolovok.toUpperCase()} (${MATERIAL_I_OTDELKA.stolbec})`);
      for (const m of MATERIAL_I_OTDELKA.stroki) {
        s.push(`  ${m.nazvanie} — ${m.znachenie}`);
      }
      s.push('');
    }
  }

  for (const r of [NAKLEJKI, BROSHYUROVKA]) {
    s.push(`${r.zagolovok.toUpperCase()} (${r.edinica})`);
    s.push(r.vvodnaya);
    for (const p of r.pozicii) s.push(`  ${p.nazvanie} — ${cenaTekstom(p.cena)}`);
    for (const n of r.primechaniya) s.push(`  ${n}`);
    s.push('');
  }

  s.push(`${RABOTA_S_MAKETOM.zagolovok.toUpperCase()} (${RABOTA_S_MAKETOM.edinica})`);
  s.push(RABOTA_S_MAKETOM.vvodnaya);
  for (const p of RABOTA_S_MAKETOM.pozicii) {
    s.push(`  ${p.nazvanie} — ${cenaTekstom(p.cena)}. ${p.chtoDelaem}`);
  }
  for (const n of RABOTA_S_MAKETOM.primechaniya) s.push(`  ${n}`);
  s.push('');

  s.push('КАК МЫ СЧИТАЕМ');
  for (const k of KAK_SCHITAEM) s.push(`  ${k.nazvanie}: ${k.tekst}`);
  s.push('');

  s.push(ZAKLYUCHENIE.zagolovok);
  for (const t of ZAKLYUCHENIE.tekst) s.push(t);
  s.push('');

  s.push(`Источник: печатный прайс от ${ISTOCHNIK.data}, ${ISTOCHNIK.stranicy}.`);
  s.push('Чего в прайсе нет — этих услуг не называть и не обещать:');
  for (const n of NET_V_PRAJSE) s.push(`  — ${n}`);

  return s.join('\n');
}
