/** Действующие акции для этой услуги. Пустой массив — акций нет. */
export function akciiDlya(scenarij: string): Akciya[] {
  return AKCII.filter(
    (a) => a.aktivna && (a.gde.length === 0 || a.gde.includes(scenarij)),
  );
}

