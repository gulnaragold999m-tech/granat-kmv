def _host(raw: str) -> str:
    """Домен из строки, которая может быть и без http://."""
    candidate = raw if "://" in raw else "http://" + raw
    try:
        host = (urlparse(candidate).hostname or "").lower()
    except ValueError:
        return ""
    return host[4:] if host.startswith("www.") else host


