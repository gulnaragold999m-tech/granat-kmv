def analyze(text: str) -> dict:
    """Разбор текста. Возвращает словарь:

        level  — 'danger' | 'suspicious' | 'watch' | 'clean'
        score  — сумма весов сработавших правил
        flags  — [(название, объяснение), ...] в порядке убывания веса
    """
    body = (text or "").lower()  # регистр не значим
    flags, score = [], 0

    def run(table):
        """Прогнать таблицу правил. Возвращает набранный вес."""
        gained = 0
        for weight, title, why, patterns in table:
            for pattern in patterns:
                if re.search(pattern, body):
                    flags.append((weight, title, why))
                    gained += weight
                    break  # правило считаем один раз, сколько бы слов ни совпало
        return gained

    score += run(RULES)

    for host in links(text):
        found = check_link(host)
        if found:
            flags.append(found)
            score += found[0]

    # Давление засчитываем, только если есть за что зацепиться. Без этого
    # обычный срочный заказ выглядел бы подозрительнее реального обмана.
    if score > 0:
        score += run(PRESSURE_RULES)

    flags.sort(key=lambda f: -f[0])

    if score >= DANGER_SCORE:
        level = "danger"
    elif score >= SUSPICIOUS_SCORE:
        level = "suspicious"
    elif score > 0:
        level = "watch"
    else:
        level = "clean"

    return {"level": level, "score": score,
            "flags": [(title, why) for _w, title, why in flags]}


def is_alarm(text: str) -> bool:
    """Стоит ли вмешаться самому, без всякой команды."""
    return analyze(text)["score"] >= ALARM_SCORE


