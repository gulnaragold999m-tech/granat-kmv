def report(text: str) -> str:
    """Готовый ответ человеку. Разбор + что делать + правила."""
    verdict = analyze(text)
    parts = [HEADERS[verdict["level"]]]

    if verdict["flags"]:
        parts.append("")
        parts.append("Что я вижу:")
        # Больше пяти признаков человек не дочитает, а первые — самые весомые.
        for title, why in verdict["flags"][:5]:
            parts.append(f"\n▪️ {title}\n   {why}")
        hidden = len(verdict["flags"]) - 5
        if hidden > 0:
            parts.append(f"\n…и ещё {hidden} признак(а) того же рода.")

    parts.append("")
    parts.append(ADVICE[verdict["level"]])

    if verdict["level"] in ("danger", "suspicious"):
        parts.append("")
        parts.append(PAUSE_RULE)

    parts.append("")
    parts.append(THREE_RULES)
    return "\n".join(parts)


