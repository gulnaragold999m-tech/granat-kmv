def _hit(text: str, triggers) -> bool:
    low = (text or "").lower()
    return any(word in low for word in triggers)


def wants_check(text: str) -> bool:
    """Просят включить проверку."""
    return _hit(text, CHECK_TRIGGERS)


def wants_stolen(text: str) -> bool:
    """Говорят, что деньги уже ушли."""
    return _hit(text, STOLEN_TRIGGERS)


def wants_exit(text: str) -> bool:
    """Просят выйти из режима проверки.

    Слово ищем только в короткой фразе и только в начале. Иначе выйти из
    проверки можно было бы случайно: в присланном тексте обмана почти всегда
    есть слово «заказ» («я оплатил ваш заказ, но перевёл лишнее») — и вместо
    разбора человек получал бы меню студии. Ровно в тот момент, когда разбор
    нужнее всего.
    """
    low = (text or "").strip().lower().strip(".!?,;:«»\"' ")
    if not low or len(low) > 24:
        return False
    return any(low == word or low.startswith(word) for word in EXIT_TRIGGERS)


# Граница «короткая просьба / присланный текст». Фраза «проверь на
# мошенников» короче; сообщение самих мошенников — длиннее.
LONG_TEXT = 60


def triage(text: str) -> str:
    """Что делать с сообщением ВНЕ режима проверки:

        'stolen' — деньги уже ушли, нужен порядок действий
        'enter'  — просят включить проверку, текста для разбора ещё нет
        'report' — прислали текст и сами назвали его подозрительным
        'alarm'  — прислали текст, ни о чём не прося, а в нём набор приёмов
        ''       — обычное сообщение, это не наше дело
    """
    body = (text or "").strip()
    if wants_stolen(body):
        return "stolen"
    if wants_check(body):
        return "enter" if len(body) < LONG_TEXT else "report"
    if body and is_alarm(body):
        return "alarm"
    return ""


def answer(text: str) -> str:
    """Ответ в режиме проверки на любой присланный текст.

    Порядок важен: «меня обманули» разбирается раньше признаков, иначе
    человек, у которого уже украли деньги, получит разбор чужого сообщения
    вместо порядка действий.
    """
    if wants_stolen(text):
        return STOLEN
    if len((text or "").strip()) < 12:
        return ("Пришлите текст целиком — так я увижу приёмы. Одного слова "
                "мало.\n\nЕсли деньги уже ушли, напишите «меня обманули».")
    return report(text)


